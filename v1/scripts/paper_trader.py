# ── State I/O ──────────────────────────────────────────────────────────────────

def load_state() -> dict:
    """
    Load portfolio state from state.json.
    Returns dict with: cash, positions, initial_capital, initialized_date,
    last_eod_date, portfolio_value. Empty dict if not yet initialised.
    """
    if not STATE_FILE.exists():
        return {}
    with open(STATE_FILE, encoding="utf-8") as f:
        return json.load(f)


def save_state(state: dict):
    """
    Persist the portfolio state dict to state.json.

    Uses json.dump with indent=2 for human readability — the file is small
    enough that pretty-printing adds no meaningful overhead.  default=str
    handles any non-JSON-serialisable values (e.g., numpy int64).

    Args:
        state: Portfolio state dict from load_state() or a modified version.
    """
    tmp = STATE_FILE.with_suffix(".json.tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=2, default=str)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, STATE_FILE)


