def get_production_method() -> tuple:
    """
    Single source of truth for production method.

    Reads V1_PRODUCTION_METHOD (pinned 2026-04-27 to atr_lev_1.5x). Reg-T
    compatible (<$100k overnight at IBKR), Pareto-dominates atr_pure after
    pl_5_10 + ts_40 exit overlay. Falls back to oos_selection.parquet auto-pick
    only when pinned method absent from OOS table.

    Returns: (method_key, display_label)
    """
    from v1.ui.styles import get_label  # lazy import: avoid circular dep
    from v1.config.params import V1_PRODUCTION_METHOD

    pinned_key = V1_PRODUCTION_METHOD
    fallback_key = "equal_weight"
    try:
        oos = pd.read_parquet("data/v1/results/oos_selection.parquet")
    except Exception:
        return pinned_key, get_label(pinned_key)

    if oos.empty or "method" not in oos.columns:
        return pinned_key, get_label(pinned_key)

    methods = set(oos["method"].astype(str))
    if pinned_key in methods or pinned_key in {_OOS_NAME_MAP.get(m, m) for m in methods}:
        return pinned_key, get_label(pinned_key)

    # Fallback: pinned not in OOS table → auto-select.
    if "oos_sharpe" not in oos.columns:
        return fallback_key, get_label(fallback_key)
    if "is_sharpe" in oos.columns:
        gaps     = oos["is_sharpe"] - oos["oos_sharpe"]
        mask     = (oos["oos_sharpe"] > 0.9) & (gaps >= -0.20) & (gaps <= 0.50)
        filtered = oos[mask]
        best_idx = filtered["oos_sharpe"].idxmax() if not filtered.empty else oos["oos_sharpe"].idxmax()
    else:
        best_idx = oos["oos_sharpe"].idxmax()
    best_method = oos.loc[best_idx, "method"]
    best_key    = _OOS_NAME_MAP.get(best_method,
                                    best_method.replace(" ", "_").replace("-", "_").lower())
    return best_key, get_label(best_key)


def _best_oos_strategy() -> str:
    """Strategy key with highest OOS Sharpe (delegates to get_production_method)."""
    key, _ = get_production_method()
    return key if key in STRATEGIES else "multi_mom_tilt"


