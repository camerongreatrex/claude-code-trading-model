# ── Constants ─────────────────────────────────────────────────────────────────
INITIAL_CAPITAL = float(CAPITAL)          # same as portfolio.py ($100k)
COMMISSION_PCT  = 0.0005                  # 0.05% per side — matches backtest
ET_ZONE         = ZoneInfo("America/New_York")


def _today_et() -> str:
    """Today's date string in US Eastern time (handles DST correctly)."""
    return str(datetime.now(ET_ZONE).date())


def _is_trading_day(d: date = None) -> bool:
    """Return True if d (default: today ET) is a weekday (Mon–Fri)."""
    if d is None:
        d = datetime.now(ET_ZONE).date()
    return d.weekday() < 5  # 5=Sat, 6=Sun

PT_DIR       = Path("data/paper_trading")
STATE_FILE   = PT_DIR / "state.json"
TRADES_FILE  = PT_DIR / "trades.csv"
HISTORY_FILE = PT_DIR / "history.csv"
PT_DIR.mkdir(parents=True, exist_ok=True)


# ── State I/O ──────────────────────────────────────────────────────────────────

def load_state() -> dict:
    """
    Load the current portfolio state from state.json.

    Returns:
        Dict with keys: cash, positions, initial_capital, initialized_date,
        last_eod_date, portfolio_value.
        Returns empty dict if state.json does not exist (not yet initialised).
    """
    if not STATE_FILE.exists():
        return {}
    with open(STATE_FILE, encoding="utf-8") as f:
        return json.load(f)


def save_state(state: dict):
    """
    Persist the portfolio state dict to state.json.

    Uses json.dump with indent=2 for human readability — the file is small
    enough that pretty-printing adds no meaningful overhead.  default=str
    handles any non-JSON-serialisable values (e.g., numpy int64).

    Args:
        state: Portfolio state dict from load_state() or a modified version.
    """
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=2, default=str)


def load_trades() -> pd.DataFrame:
    """
    Load the full trade log from trades.csv.

    Returns:
        DataFrame with all BUY/SELL records since initialisation.
        Returns empty DataFrame if trades.csv does not exist yet (no trades made).
    """
    if not TRADES_FILE.exists():
        return pd.DataFrame()
    df = pd.read_csv(TRADES_FILE)
    df["date"] = pd.to_datetime(df["date"])
    return df


def load_history() -> pd.DataFrame:
    """
    Load the daily portfolio snapshot history from history.csv.

    Returns:
        DataFrame sorted by date with columns: date, portfolio_value, cash,
        invested, n_positions, daily_return.
        Returns empty DataFrame if history.csv does not exist.
    """
    if not HISTORY_FILE.exists():
        return pd.DataFrame()
    df = pd.read_csv(HISTORY_FILE)
    df["date"] = pd.to_datetime(df["date"])
    return df.sort_values("date").reset_index(drop=True)


def _append_csv(path: Path, record: dict):
    """
    Append a single record dict to a CSV file (creates header on first write).

    Using append mode ("a") rather than reading and rewriting the full CSV
    makes this O(1) regardless of how many records already exist.  The
    trade log and history file can grow indefinitely without performance
    degradation.

    Args:
        path:   Path to the CSV file.
        record: Dict of {column_name: value} for one row.
    """
    row = pd.DataFrame([record])
    row.to_csv(path, mode="a", header=not path.exists(), index=False)


# ── Live data fetcher (yfinance, free, no API key) ────────────────────────────

def _fetch_daily(ticker: str, lookback_days: int = 700,
                 end_date: "date | None" = None) -> pd.DataFrame:
    """
    Download ``lookback_days`` of daily OHLCV for a single ticker.

    Used by compute_live_signals() to get enough history for the full
    feature engineering and signal generation pipeline:
      - MA200 requires 200 trading days ≈ 290 calendar days
      - ATR and RSI warm-up adds ~30 days
      - Total: 320+ calendar days recommended; 700 is used for safety margin

    Args:
        ticker:        Yahoo Finance ticker symbol.
        lookback_days: Calendar days of history to fetch (default 700).
        end_date:      If provided, fetch data ending at this date (inclusive).
                       Used by catch-up mode to replay a historical trading day.
                       Defaults to today.

    Returns:
        OHLCV DataFrame indexed by timezone-naive date.
    """
    end   = datetime(end_date.year, end_date.month, end_date.day) if end_date else datetime.today()
    start = end - timedelta(days=lookback_days)
    df = yf.download(
        ticker,
        start=start.strftime("%Y-%m-%d"),
        end=end.strftime("%Y-%m-%d"),
        auto_adjust=True, progress=False,
        multi_level_index=False,
    )
    if isinstance(df.columns, pd.MultiIndex):
        df.columns = df.columns.droplevel(1)
    df.index = pd.to_datetime(df.index)
    if df.index.tz is not None:
        df.index = df.index.tz_localize(None)
    df.index.name = "Date"
    return df


def fetch_intraday_batch(tickers: list) -> dict:
    """
    Fetch today's 5-minute OHLCV bars for a batch of tickers.

    Used by the dashboard's intraday equity curve and the VS S&P chart.
    Returns only bars within today's regular trading session (09:25–16:05 ET).

    Key implementation details:
      - Uses yf.Ticker().history() rather than yf.download() — the Ticker API
        returns tz-aware America/New_York timestamps directly, avoiding the
        UTC-to-ET conversion bug that caused morning bars to be dropped.
      - period="2d" is used instead of period="1d" because yfinance sometimes
        returns incomplete early-session data with period="1d" during live hours.
      - The market-hours filter MUST run after tz_convert() — comparing UTC
        timestamps against ET thresholds would silently drop all morning bars.

    Args:
        tickers: List of ticker symbols to fetch (^GSPC always included by caller).

    Returns:
        Dict[ticker -> DataFrame] where each DataFrame has columns
        [Open, High, Low, Close, Volume] indexed by timezone-naive ET strings.
        Tickers that fail are silently omitted.
    """
    now_et    = pd.Timestamp.now(tz='America/New_York')
    today_str = now_et.strftime('%Y-%m-%d')
    mkt_open  = pd.Timestamp(today_str + " 09:25:00")   # naive ET
    mkt_close = pd.Timestamp(today_str + " 16:05:00")   # naive ET

    results = {}
    for ticker in tickers:
        try:
            # Ticker.history() returns tz-aware America/New_York timestamps
            # directly — more complete during live market hours than yf.download()
            raw = yf.Ticker(ticker).history(period="2d", interval="5m")
            if raw.empty:
                continue
            if isinstance(raw.columns, pd.MultiIndex):
                raw.columns = raw.columns.droplevel(1)
            # Convert tz-aware ET → naive ET strings (wall-clock, DST-correct)
            et_idx = raw.index.tz_convert('America/New_York')
            raw.index = pd.DatetimeIndex(et_idx.strftime('%Y-%m-%d %H:%M:%S'))
            # Filter to today's regular trading hours (comparison is naive ET vs naive ET)
            raw = raw[(raw.index >= mkt_open) & (raw.index <= mkt_close)]
            if not raw.empty:
                results[ticker] = raw
        except Exception:
            pass
    return results


# ── Strategy pipeline (same code path as backtest) ────────────────────────────

def compute_live_signals() -> dict:
    """
    Run the full strategy pipeline on live yfinance data and return today's signals.

    This is the core function that paper_trader and scheduler call.  It
    replicates the entire offline pipeline (data_pipeline → feature_engineering
    → signal_generation) using fresh yfinance data instead of stored parquets.

    Steps:
      1. Fetch last 700 calendar days of OHLCV via yfinance (_fetch_daily)
      2. engineer() — computes all technical features (ATR, RSI, MACD, ADX, ...)
      3. generate() — applies MA crossover + RSI filter + min-hold + trailing stop
      4. Extract the latest signal row for each ticker

    Returns:
        Dict[ticker -> signal_info_dict] where each dict contains:
          signal    — 0 or 1 (regime signal after all post-processors)
          composite — 0 or 1 (score-based signal)
          close     — latest adjusted close price
          atr       — latest 14-day ATR
          rsi       — latest RSI-14
          date      — string date of the latest available bar
        Tickers that fail (network error, insufficient history) are omitted.
    """
    macro   = load_macro()
    results = {}

    for ticker in TICKER_LIST:
        print(f"  {ticker:<6}", end=" ", flush=True)
        try:
            raw  = _fetch_daily(ticker)
            feat = engineer(raw)
            sig  = generate(feat, ticker, macro)

            if sig.empty:
                print("no signal data")
                continue

            latest_sig  = int(sig["signal_regime"].iloc[-1])
            latest_comp = int(sig["signal_composite"].iloc[-1])
            latest_atr  = float(feat["atr_14"].iloc[-1])
            latest_close= float(feat["Close"].iloc[-1])
            latest_rsi  = float(feat["rsi_14"].iloc[-1])

            # Donchian breakout detection
            try:
                _close_s   = feat["Close"]
                _don_high  = feat["High"].rolling(20).max() if "High" in feat.columns else _close_s.rolling(20).max()
                _don_low   = feat["Low"].rolling(20).min()  if "Low"  in feat.columns else _close_s.rolling(20).min()
                _don_w     = (_don_high - _don_low) / _close_s.replace(0, np.nan)
                _w_rank    = _don_w.rolling(252, min_periods=63).rank(pct=True)
                _squeeze   = (_w_rank < 0.20)
                _breakout  = (_close_s >= _don_high)
                _recent_sq = _squeeze.rolling(5, min_periods=1).max().astype(bool)
                latest_breakout = int(bool(_breakout.iloc[-1]))
                latest_squeeze  = int(bool(_recent_sq.iloc[-1]))
            except Exception:
                latest_breakout = 0
                latest_squeeze  = 0

            # For bonds/commodities with signal=-1 (short), log and keep signal=0
            # for paper trading execution but preserve the raw signal for display.
            asset_cls   = ASSET_CLASS.get(ticker, "")
            paper_signal = latest_sig
            if asset_cls in ("bond", "commodity") and latest_sig == -1:
                print(f"  [{ticker}] short signal on {asset_cls} — keeping flat for paper trading")
                paper_signal = 0

            results[ticker] = {
                "signal"       : paper_signal,
                "raw_signal"   : latest_sig,
                "composite"    : latest_comp,
                "close"        : latest_close,
                "atr"          : latest_atr,
                "rsi"          : latest_rsi,
                "breakout"     : latest_breakout,
                "squeeze"      : latest_squeeze,
                "asset_class"  : asset_cls,
                "date"         : str(feat.index[-1].date()),
            }
            print(f"${latest_close:>8.2f}  {'LONG' if latest_sig else 'FLAT'}")
        except Exception as e:
            print(f"ERROR {e}")

    return results


# ── ATR position sizing (mirrors portfolio.py atr_sizes) ─────────────────────

def _atr_size(pv: float, atr: float, price: float) -> float:
    """
    Compute the ATR-based dollar position size for a single ticker.

    Mirrors portfolio.atr_sizes() for a single asset:
      dollar_risk = portfolio_value × RISK_PER_TRADE
      shares      = dollar_risk / ATR
      position $  = shares × price

    Caps at MAX_POSITION_PCT × portfolio_value to prevent over-concentration.
    Falls back to equal-weight (capital / n_tickers) if ATR is zero or missing.

    Args:
        pv:    Current portfolio value in dollars.
        atr:   14-day Average True Range for the ticker.
        price: Current share price.

    Returns:
        Target position size in dollars.
    """
    if not atr or atr <= 0:
        return min(pv / len(TICKER_LIST), pv * MAX_POSITION_PCT)
    dollar_risk = pv * RISK_PER_TRADE
    dollar_pos  = (dollar_risk / atr) * price
    return min(dollar_pos, pv * MAX_POSITION_PCT)


# ── Trade execution ───────────────────────────────────────────────────────────

def _buy(state: dict, ticker: str, price: float,
         dollar_amount: float, reason: str, trade_date: str) -> dict:
    """
    Execute a simulated BUY order and update state.

    Args:
        state:         Current portfolio state dict (modified in place).
        ticker:        Ticker to buy.
        price:         Execution price (typically yesterday's close).
        dollar_amount: Target position size in dollars.
        reason:        String label for the trade log (e.g., "signal_entry").
        trade_date:    ISO date string for the trade record.

    Returns:
        Updated state dict.

    Behaviour:
      - No averaging into existing positions (avoids pyramiding risk).
      - If dollar_amount > available cash, the order is scaled down to 97%
        of remaining cash (small buffer for rounding).
      - Orders smaller than $200 are skipped (minimum viable position size).
      - Commission is COMMISSION_PCT (0.05%) of the position notional,
        matching the backtest transaction cost assumption.
    """
    if ticker in state["positions"]:
        return state   # no averaging into existing positions

    commission = dollar_amount * COMMISSION_PCT
    total_cost = dollar_amount + commission

    if total_cost > state["cash"] * 1.01:
        dollar_amount = state["cash"] * 0.97
        commission    = dollar_amount * COMMISSION_PCT
        total_cost    = dollar_amount + commission

    if dollar_amount < 200:
        return state

    shares = dollar_amount / price
    state["cash"] -= total_cost
    state["positions"][ticker] = {
        "shares"    : shares,
        "entry_price": price,
        "entry_date" : trade_date,
        "cost_basis" : dollar_amount,
    }
    _append_csv(TRADES_FILE, {
        "date": trade_date, "ticker": ticker, "action": "BUY",
        "shares": round(shares, 6), "price": round(price, 4),
        "value": round(dollar_amount, 2), "commission": round(commission, 2),
        "pnl": "", "reason": reason,
    })
    print(f"  BUY  {ticker:<6}  {shares:.3f} sh @ ${price:.2f}"
          f"  (${dollar_amount:,.0f})  [{reason}]")
    return state


def _sell(state: dict, ticker: str, price: float,
          reason: str, trade_date: str) -> dict:
    """
    Execute a simulated SELL order and update state.

    Args:
        state:      Current portfolio state dict (modified in place).
        ticker:     Ticker to sell (must be in state["positions"]).
        price:      Execution price (typically yesterday's close).
        reason:     String label for the trade log (e.g., "signal_exit").
        trade_date: ISO date string for the trade record.

    Returns:
        Updated state dict.

    Behaviour:
      - Sells the full position (no partial sells — the strategy is always
        fully in or fully out, matching the 0/1 signal model).
      - Commission is 0.05% of gross proceeds.
      - Realised P&L = net proceeds − original cost basis.
    """
    if ticker not in state["positions"]:
        return state
    pos        = state["positions"].pop(ticker)
    proceeds   = pos["shares"] * price
    commission = proceeds * COMMISSION_PCT
    net        = proceeds - commission
    pnl        = net - pos["cost_basis"]
    state["cash"] += net
    _append_csv(TRADES_FILE, {
        "date": trade_date, "ticker": ticker, "action": "SELL",
        "shares": round(pos["shares"], 6), "price": round(price, 4),
        "value": round(proceeds, 2), "commission": round(commission, 2),
        "pnl": round(pnl, 2), "reason": reason,
    })
    pnl_s = f"+${pnl:,.0f}" if pnl >= 0 else f"-${abs(pnl):,.0f}"
    print(f"  SELL {ticker:<6}  {pos['shares']:.3f} sh @ ${price:.2f}"
          f"  P&L {pnl_s}  [{reason}]")
    return state


def _portfolio_value(state: dict, prices: dict) -> float:
    """
    Compute total portfolio value: cash + market value of all open positions.

    Uses live prices where available.  Falls back to the position's entry
    price if no live price is available for a ticker (e.g., market closed,
    data fetch failed).

    Args:
        state:  Portfolio state dict with "cash" and "positions".
        prices: Dict[ticker -> latest_price] from compute_live_signals() or
                get_intraday_curve().

    Returns:
        Total portfolio value in dollars.
    """
    return state["cash"] + sum(
        pos["shares"] * prices.get(t, pos["entry_price"])
        for t, pos in state["positions"].items()
    )


# ── Init ──────────────────────────────────────────────────────────────────────

def init_positions():
    """
    One-time portfolio initialisation.  Run once at strategy launch.

    Fetches live signals, enters all tickers with signal=1, and saves
    the initial state.  This simulates the moment you decide to start
    paper trading the strategy.

    Capital distribution:
      ATR sizing is capped at capital/n_longs per position to ensure all
      active signals are represented.  Raw ATR sizes for many simultaneous
      LONG signals can sum to more than 100% of capital (they are designed
      for sequential entries, not simultaneous deployment).  The cap
      distributes capital evenly on day 1.

    Note:
      state["portfolio_value"] is set to INITIAL_CAPITAL (not the actual
      post-commission entry value) so that "Portfolio Today %" on day 1
      is measured from the $100k baseline, not from the slippage-reduced
      actual entry.  This matches how TradingView and institutional systems
      display intraday performance.
    """
    if STATE_FILE.exists():
        print(f"Already initialised.  Delete {STATE_FILE} to reset.")
        return

    today_str = str(date.today())
    print(f"Initialising paper portfolio  ({today_str})\n")
    print("Running strategy pipeline on live data...\n")

    signals = compute_live_signals()
    prices  = {t: s["close"] for t, s in signals.items()}

    state = {
        "cash"            : INITIAL_CAPITAL,
        "positions"       : {},
        "initial_capital" : INITIAL_CAPITAL,
        "initialized_date": today_str,
        "last_eod_date"   : today_str,
        "portfolio_value" : INITIAL_CAPITAL,
    }

    longs = [t for t, s in signals.items() if s["signal"] == 1]
    print(f"\n{len(longs)}/{len(signals)} tickers: LONG signal — entering positions...\n")

    # Distribute capital across ALL active signals.
    # ATR sizing can exceed 100% of capital when many tickers are LONG simultaneously,
    # so we cap each position at capital / n_longs to ensure all signals are represented.
    per_position_cap = (INITIAL_CAPITAL * 0.97) / max(len(longs), 1)

    for ticker in longs:
        sig  = signals[ticker]
        size = min(_atr_size(INITIAL_CAPITAL, sig["atr"], sig["close"]), per_position_cap)
        state = _buy(state, ticker, sig["close"], size,
                     reason="init_golden_cross", trade_date=today_str)

    pv = _portfolio_value(state, prices)
    # Store INITIAL_CAPITAL as the baseline so "Portfolio Today" on day 1
    # is measured from $100k, not the post-commission entry value.
    state["portfolio_value"] = INITIAL_CAPITAL

    _append_csv(HISTORY_FILE, {
        "date": today_str, "portfolio_value": round(pv, 2),
        "cash": round(state["cash"], 2),
        "invested": round(pv - state["cash"], 2),
        "n_positions": len(state["positions"]), "daily_return": 0.0,
    })
    save_state(state)

    print(f"\n{'='*52}")
    print(f"  Positions   : {len(state['positions'])}")
    print(f"  Invested    : ${pv - state['cash']:>10,.2f}")
    print(f"  Cash        : ${state['cash']:>10,.2f}")
    print(f"  Total value : ${pv:>10,.2f}")
    print(f"{'='*52}")
    print(f"\nState -> {STATE_FILE}")
    print("Run 'python paper_trader.py run' (or scheduler.py) after each close.")


# ── End-of-day update ─────────────────────────────────────────────────────────

def end_of_day_update():
    """
    Run the daily strategy update: fetch signals, execute exits/entries, snapshot.

    Called by scheduler.py at 4:45 PM ET on weekdays.  Also callable via
    the dashboard's "Run EOD Update" button and directly from the CLI.

    Execution order:
      1. Load current state (positions, cash, previous portfolio value)
      2. Fetch live signals via compute_live_signals()
      3. EXITS first: sell any open position where signal_regime == 0
         (death cross fired, trailing stop hit, or RSI filter — the strategy
         layer already decided; this function just executes)
      4. ENTRIES: buy any ticker where signal_regime == 1 and not yet long,
         sized by ATR, if sufficient cash is available
      5. Snapshot: compute new portfolio value, daily return, total return;
         append to history.csv; save updated state.json

    Note:
      The signal used here is ``signal_regime`` (the primary MA-crossover
      signal with all post-processors), NOT ``signal_composite``.  The
      composite score is shown on the dashboard for informational purposes
      but the regime signal is what actually drives trades.
    """
    state = load_state()
    if not state:
        print("No portfolio found.  Run 'python paper_trader.py init' first.")
        return

    today_str  = _today_et()

    # Markets are closed on weekends — skip silently
    if not _is_trading_day():
        print(f"Today is {datetime.now(ET_ZONE).strftime('%A')} — markets are closed, skipping EOD.")
        return

    # Skip if already ran today (prevents duplicates from scheduler + manual + GH Actions)
    if state.get("last_eod_date") == today_str:
        print(f"EOD already ran for {today_str} — skipping.")
        return

    prev_value = state.get("portfolio_value", INITIAL_CAPITAL)

    print(f"\nEnd-of-day update  ({today_str})\n")
    print("Running strategy pipeline on live data...\n")

    signals = compute_live_signals()
    prices  = {t: s["close"] for t, s in signals.items()}

    # ── Exits: sell anything where signal_regime flipped to 0 ────────────────
    for ticker in list(state["positions"]):
        if ticker not in signals:
            continue
        if signals[ticker]["signal"] == 0:
            # Signal is 0 — could be death cross, trailing stop, or any filter.
            # The strategy layer already decided; execution just acts on it.
            state = _sell(state, ticker, prices[ticker],
                          reason="signal_exit", trade_date=today_str)

    # ── Entries: buy anything where signal_regime is 1 and not already long ──
    current_longs = set(state["positions"])
    pv = _portfolio_value(state, prices)

    for ticker in TICKER_LIST:
        if ticker in current_longs or ticker not in signals:
            continue
        if signals[ticker]["signal"] == 1:
            sig  = signals[ticker]
            size = _atr_size(pv, sig["atr"], sig["close"])
            if state["cash"] >= size * 1.01:
                state = _buy(state, ticker, sig["close"], size,
                             reason="signal_entry", trade_date=today_str)

    # ── Snapshot ──────────────────────────────────────────────────────────────
    pv        = _portfolio_value(state, prices)
    daily_ret = (pv / prev_value - 1) if prev_value > 0 else 0.0
    total_ret = (pv / INITIAL_CAPITAL - 1) * 100

    state["portfolio_value"] = pv
    state["last_eod_date"]   = today_str
    save_state(state)

    _append_csv(HISTORY_FILE, {
        "date": today_str, "portfolio_value": round(pv, 2),
        "cash": round(state["cash"], 2),
        "invested": round(pv - state["cash"], 2),
        "n_positions": len(state["positions"]),
        "daily_return": round(daily_ret * 100, 4),
    })

    print(f"\n{'='*52}")
    print(f"  Portfolio value : ${pv:>10,.2f}")
    print(f"  Cash            : ${state['cash']:>10,.2f}")
    print(f"  Positions       : {len(state['positions'])}")
    print(f"  Daily return    : {daily_ret*100:>+8.2f}%")
    print(f"  Total return    : {total_ret:>+8.2f}%")
    print(f"{'='*52}")


# ── Catch-up (replay missed trading days when PC was off) ─────────────────────

def _trading_days_between(start: date, end: date) -> list:
    """
    Return all weekdays strictly between start (exclusive) and end (exclusive).

    Note: does not filter US market holidays.  On holiday dates yfinance will
    return the previous trading day's close, so the EOD update runs but
    produces a zero-return snapshot — harmless and self-correcting.

    Args:
        start: First date to exclude (last processed date).
        end:   Last date to exclude (today — not yet closed).

    Returns:
        Sorted list of date objects for missed trading days.
    """
    days   = []
    cursor = start + timedelta(days=1)
    while cursor < end:
        if cursor.weekday() < 5:   # 0=Mon … 4=Fri
            days.append(cursor)
        cursor += timedelta(days=1)
    return days


def _compute_signals_as_of(as_of: date) -> dict:
    """
    Run the full strategy pipeline using data available up to ``as_of``.

    Identical to compute_live_signals() except:
      - yfinance fetch ends at ``as_of`` (not today)
      - Data is trimmed to rows ≤ as_of so the pipeline never sees future prices

    This guarantees the same signal the live run would have produced on that
    date — used exclusively by catchup() to replay missed market days.

    Args:
        as_of: The historical trading date to simulate.

    Returns:
        Dict[ticker -> signal_info_dict], same schema as compute_live_signals().
    """
    macro   = load_macro()
    results = {}

    for ticker in TICKER_LIST:
        try:
            # Fetch data ending the day after as_of so yfinance includes as_of's close
            raw  = _fetch_daily(ticker, end_date=as_of + timedelta(days=1))
            # Trim to as_of — prevent any look-ahead into future bars
            raw  = raw[raw.index <= pd.Timestamp(as_of)]
            if len(raw) < 60:
                continue

            feat = engineer(raw)
            sig  = generate(feat, ticker, macro)
            if sig.empty:
                continue

            results[ticker] = {
                "signal"   : int(sig["signal_regime"].iloc[-1]),
                "composite": int(sig["signal_composite"].iloc[-1]),
                "close"    : float(feat["Close"].iloc[-1]),
                "atr"      : float(feat["atr_14"].iloc[-1]),
                "rsi"      : float(feat["rsi_14"].iloc[-1]),
                "date"     : str(as_of),
            }
        except Exception as e:
            print(f"  {ticker}: {e}")

    return results


def _end_of_day_update_for_date(as_of: date) -> None:
    """
    Replay a single historical EOD update using prices from ``as_of``.

    Used by catchup() to process trading days the PC missed.  Internally
    identical to end_of_day_update() but uses _compute_signals_as_of()
    instead of compute_live_signals() so prices come from yfinance history
    rather than the live feed.

    Args:
        as_of: The historical trading date to replay.
    """
    state = load_state()
    if not state:
        return

    as_of_str  = str(as_of)

    # Skip weekends — no market data, no trades
    if not _is_trading_day(as_of):
        return

    # Skip if this date was already processed (prevents duplicates from
    # concurrent dashboard + scheduler catch-up or interrupted previous runs)
    if state.get("last_eod_date", "") >= as_of_str:
        print(f"  Catch-up: {as_of_str} — already processed, skipping")
        return

    prev_value = state.get("portfolio_value", INITIAL_CAPITAL)

    print(f"  Catch-up: {as_of_str} ...", end=" ", flush=True)
    signals = _compute_signals_as_of(as_of)
    if not signals:
        print("no signals — skipped")
        return

    prices = {t: s["close"] for t, s in signals.items()}

    # Exits
    for ticker in list(state["positions"]):
        if ticker in signals and signals[ticker]["signal"] == 0:
            state = _sell(state, ticker, prices[ticker],
                          reason="catchup_signal_exit", trade_date=as_of_str)

    # Entries
    current_longs = set(state["positions"])
    pv = _portfolio_value(state, prices)
    for ticker in TICKER_LIST:
        if ticker in current_longs or ticker not in signals:
            continue
        if signals[ticker]["signal"] == 1:
            size = _atr_size(pv, signals[ticker]["atr"], signals[ticker]["close"])
            if state["cash"] >= size * 1.01:
                state = _buy(state, ticker, signals[ticker]["close"], size,
                             reason="catchup_signal_entry", trade_date=as_of_str)

    # Snapshot
    pv        = _portfolio_value(state, prices)
    daily_ret = (pv / prev_value - 1) if prev_value > 0 else 0.0
    state["portfolio_value"] = pv
    state["last_eod_date"]   = as_of_str
    save_state(state)

    _append_csv(HISTORY_FILE, {
        "date": as_of_str, "portfolio_value": round(pv, 2),
        "cash": round(state["cash"], 2),
        "invested": round(pv - state["cash"], 2),
        "n_positions": len(state["positions"]),
        "daily_return": round(daily_ret * 100, 4),
    })
    print(f"done  (${pv:,.0f}  {daily_ret*100:+.2f}%)")


def catchup() -> int:
    """
    Detect and replay any trading days missed while the PC was off.

    Called automatically by the scheduler at startup.  Compares
    ``last_eod_date`` in state.json against today's date and processes
    each missed weekday in chronological order.

    Returns:
        Number of days replayed (0 if already up to date).

    Example:
        PC off Thursday–Sunday → scheduler starts Monday morning →
        catchup() replays Thursday and Friday before the live 4:45 run.
    """
    state = load_state()
    if not state:
        return 0

    last_str = state.get("last_eod_date")
    if not last_str:
        return 0

    last  = date.fromisoformat(last_str)
    today = datetime.now(ET_ZONE).date()

    missed = _trading_days_between(last, today)
    if not missed:
        return 0

    print(f"\nCatch-up: {len(missed)} missed trading day(s) detected")
    print(f"  Last processed : {last_str}")
    print(f"  Today          : {today}\n")

    for d in missed:
        _end_of_day_update_for_date(d)

    print(f"\nCatch-up complete — {len(missed)} day(s) replayed.\n")
    return len(missed)


# ── Intraday curve (used by dashboard) ────────────────────────────────────────

def get_intraday_curve() -> tuple:
    """
    Build a live 5-minute OHLC curve of total portfolio value for the dashboard.

    Aggregates intraday bars across all open positions:
      portfolio_value[t] = sum(shares_i × price_i[t] for i in positions) + cash

    Also builds a normalized SPY benchmark curve starting at the same value
    as the portfolio's first intraday bar, so both lines are directly comparable
    on the chart without any vertical offset.

    Returns:
        4-tuple of:
          result         — DataFrame(index=ET-naive datetime, columns=[open,high,low,close])
                           representing the total portfolio value in dollars.
          last_prices    — Dict[ticker -> float] of the most recent 5-min close
                           for each position (used in the positions table).
          spy_curve      — pd.Series of SPY benchmark values in dollars,
                           normalised to portfolio_open at market open.
          spy_pct_from_prev — Float SPY % change from yesterday's official
                           close, or None if the daily data fetch failed.
                           None signals the dashboard to fall back to the
                           first-bar baseline (misses the overnight gap).

    Data quality notes:
      - Forward-fill is applied before summing across tickers to prevent
        artificial dips when one ticker's 5-min bar arrives late.
      - A sanity check rejects results outside [10%, 250%] of INITIAL_CAPITAL —
        these indicate an intermittent yfinance price spike.
      - spy_pct_from_prev uses period="5d" daily data filtered to dates BEFORE
        today.  Using period="2d" was a bug — the incomplete today row caused
        the calculation to return ~0% change.
    """
    _empty_spy = pd.Series(dtype=float)
    empty = (pd.DataFrame(columns=["open", "high", "low", "close"]), {}, _empty_spy, None)
    state = load_state()
    if not state or not state.get("positions"):
        return empty

    cash      = state["cash"]
    positions = state["positions"]
    # Always include ^GSPC (the actual S&P 500 index) so the benchmark curve
    # is available.  Using ^GSPC instead of the SPY ETF means the % shown
    # matches Yahoo Finance and TradingView exactly (SPY's auto_adjust distorts it).
    intraday  = fetch_intraday_batch(list(set(list(positions) + ["^GSPC"])))

    col_map     = {"open": "Open", "high": "High", "low": "Low", "close": "Close"}
    all_series  = {key: {} for key in col_map}   # key -> {ticker: weighted series}
    last_prices = {}

    for ticker, pos in positions.items():
        if ticker not in intraday:
            continue
        df = intraday[ticker]
        for key, yf_col in col_map.items():
            col = df[yf_col] if yf_col in df.columns else None
            if col is None:
                continue
            if isinstance(col, pd.DataFrame):
                col = col.iloc[:, 0]
            all_series[key][ticker] = col * pos["shares"]
        # last price per ticker for the positions table
        close_col = df["Close"] if "Close" in df.columns else df.iloc[:, 3]
        if isinstance(close_col, pd.DataFrame):
            close_col = close_col.iloc[:, 0]
        if not close_col.empty:
            last_prices[ticker] = float(close_col.iloc[-1])

    if not all_series["close"]:
        return empty

    # Forward-fill before summing: tickers with a missing latest bar use their
    # previous price rather than contributing 0, which caused artificial portfolio
    # value dips every time one ticker lagged behind the others.
    ohlc_sums = {}
    for key, ticker_series in all_series.items():
        if not ticker_series:
            continue
        combined = pd.concat(list(ticker_series.values()), axis=1)
        combined = combined.ffill()
        ohlc_sums[key] = combined.sum(axis=1)

    if "close" not in ohlc_sums:
        return empty

    result = pd.DataFrame({k: v + cash for k, v in ohlc_sums.items()})
    result.index = pd.to_datetime(result.index)
    if result.index.tz is not None:
        et = result.index.tz_convert('America/New_York')
        result.index = pd.DatetimeIndex(et.strftime('%Y-%m-%d %H:%M:%S'))
    # fetch_intraday_batch already filters to today's regular hours — drop any
    # remaining NaN rows from the ffill/concat alignment step only.
    result = result.dropna(how="all")

    # Sanity check: reject clearly bad yfinance data (intermittent price spikes)
    if not result.empty:
        last_close = float(result["close"].iloc[-1])
        if last_close > INITIAL_CAPITAL * 2.5 or last_close < INITIAL_CAPITAL * 0.1:
            return empty

    today_str = pd.Timestamp.now(tz='America/New_York').strftime('%Y-%m-%d')

    # S&P 500 benchmark: use ^GSPC (the actual index, not the SPY ETF) so the
    # percentage displayed matches Yahoo Finance and TradingView exactly.
    # SPY with auto_adjust=True adjusts for dividends which distorts the daily %.
    #
    # Normalize spy_curve so its LAST bar equals prev_pv × (1 + gspc_pct/100).
    # This anchors BOTH the main equity chart and the vs-S&P chart to the same
    # close-to-close baseline — "line above/below" always matches the metric.
    spy_curve         = _empty_spy
    spy_pct_from_prev = None   # None = daily fetch failed; dashboard falls back to first-bar %
    prev_pv_state     = state.get("portfolio_value", INITIAL_CAPITAL)
    if "^GSPC" in intraday:
        gspc_df  = intraday["^GSPC"]
        gspc_col = gspc_df["Close"] if "Close" in gspc_df.columns else gspc_df.iloc[:, 3]
        if isinstance(gspc_col, pd.DataFrame):
            gspc_col = gspc_col.iloc[:, 0]
        gspc_today = gspc_col
        if not gspc_today.empty:
            # Compute ^GSPC % from yesterday's official close.
            # period="5d" ensures enough rows; filter to dates < today so the
            # incomplete in-progress row never corrupts the prev-close calculation.
            try:
                gspc_daily = yf.download("^GSPC", period="5d", interval="1d",
                                         auto_adjust=True, progress=False)
                if isinstance(gspc_daily.columns, pd.MultiIndex):
                    gspc_daily.columns = gspc_daily.columns.droplevel(1)
                gspc_dc = gspc_daily["Close"] if "Close" in gspc_daily.columns else gspc_daily.iloc[:, 3]
                if isinstance(gspc_dc, pd.DataFrame):
                    gspc_dc = gspc_dc.iloc[:, 0]
                gspc_dc.index = pd.to_datetime(gspc_dc.index).tz_localize(None).normalize()
                today_ts  = pd.Timestamp(today_str)
                prev_rows = gspc_dc[gspc_dc.index < today_ts]
                if not prev_rows.empty:
                    gspc_prev_close = float(prev_rows.iloc[-1])
                    if gspc_prev_close > 0:
                        spy_pct_from_prev = (float(gspc_today.iloc[-1]) / gspc_prev_close - 1) * 100
            except Exception:
                pass

            # Build spy_curve anchored to the close-to-close baseline.
            # last bar = prev_pv × (1 + spy_pct_from_prev/100) guarantees
            # chart visual and outperforming/underperforming metric always agree.
            gspc_last = float(gspc_today.iloc[-1])
            if spy_pct_from_prev is not None and prev_pv_state > 0 and gspc_last > 0:
                spy_target = (1 + spy_pct_from_prev / 100) * prev_pv_state
                spy_curve  = gspc_today * (spy_target / gspc_last)
            elif gspc_last > 0:
                # Fallback when daily fetch fails: intraday-only (no overnight gap)
                portfolio_open = float(result["close"].iloc[0]) if not result.empty else prev_pv_state
                spy_curve = gspc_today / float(gspc_today.iloc[0]) * portfolio_open

    return result, last_prices, spy_curve, spy_pct_from_prev


# ── Status ─────────────────────────────────────────────────────────────────────

def print_status():
    """
    Print a formatted summary of the current portfolio state to stdout.

    Shows portfolio value, cash, total return, and a list of all open
    positions with shares, entry price, and entry date.

    Also runs compute_live_signals() to display the "Paper Action" column
    showing what the paper trader would do vs what the raw signal says,
    coloured orange when they differ (bond/commodity short signals kept flat).
    """
    state = load_state()
    if not state:
        print("No portfolio found.  Run 'python paper_trader.py init'")
        return
    pv        = state.get("portfolio_value", INITIAL_CAPITAL)
    total_ret = (pv / INITIAL_CAPITAL - 1) * 100
    print(f"\nPaper Portfolio  ({state.get('last_eod_date','?')})")
    print(f"{'='*52}")
    print(f"  Portfolio value : ${pv:>10,.2f}")
    print(f"  Cash            : ${state['cash']:>10,.2f}")
    print(f"  Total return    : {total_ret:>+8.2f}%")
    print(f"\n  Open positions ({len(state['positions'])}):")
    for ticker, pos in state["positions"].items():
        print(f"    {ticker:<6}  {pos['shares']:.3f} sh  "
              f"@ ${pos['entry_price']:.2f}  since {pos['entry_date']}")

    # Live signal + paper action table
    print(f"\n  Live signal state (paper action vs raw signal):")
    print(f"  {'Ticker':<8} {'Signal':>8} {'Paper Action':>14} {'Note'}")
    print(f"  {'-'*50}")
    try:
        live_sigs = compute_live_signals()
        for t, s in live_sigs.items():
            raw_s  = s.get("raw_signal", s["signal"])
            paper_s = s["signal"]
            raw_lbl   = "LONG" if raw_s == 1 else ("SHORT" if raw_s == -1 else "FLAT")
            paper_lbl = "LONG" if paper_s == 1 else "FLAT"
            note = "(short→flat)" if raw_s == -1 and paper_s == 0 else ""
            differ = raw_s != paper_s
            # Use ANSI orange for differing signals in terminal
            prefix = "\033[33m" if differ else ""
            suffix = "\033[0m"  if differ else ""
            print(f"  {prefix}{t:<8} {raw_lbl:>8} {paper_lbl:>14}   {note}{suffix}")
    except Exception as e:
        print(f"  (could not fetch live signals: {e})")


