"""
paper_trader.py
---------------
Execution engine for live paper trading.  Runs the same strategy code as
the backtest — no divergence between simulation and live operation.

Architecture: separation of concerns
─────────────────────────────────────
  WHAT to trade  ← signal_generation.generate()   (MA crossover + filters)
  HOW MUCH       ← portfolio.atr_sizes()           (ATR-normalised sizing)
  WHEN to act    ← scheduler.py                    (4:45 PM ET, weekdays)
  EXECUTION      ← _buy(), _sell()                 (this file only)

This separation means the strategy can be improved in signal_generation.py
and the improvement automatically applies to BOTH the backtest AND the live
paper trader.  There is no "paper trader version" of the signal logic.

Post-processors applied (same constants as backtest)
─────────────────────────────────────────────────────
  RSI entry filter    — skip entries when RSI_14 > 70 (overbought at open)
  ATR trailing stop   — exit if price drops 3× ATR below the trailing high
  Min-hold filter     — stay long at least 5 days to prevent same-week whipsaws

State files (data/paper_trading/)
───────────────────────────────────
  state.json       — current cash, open positions, last portfolio value
  trades.csv       — append-only trade log (BUY / SELL entries)
  history.csv      — daily snapshot: date, portfolio_value, cash, n_positions
  orders_tomorrow.json — generated by scheduler.py; next day's expected orders

Usage
─────
  python paper_trader.py init    — one-time setup: enter all LONG signals now
  python paper_trader.py run     — EOD update (run after 4:30 PM ET)
  python paper_trader.py status  — print current state without trading
  (called automatically by scheduler.py and dashboard.py's "Run EOD Update" button)
"""

